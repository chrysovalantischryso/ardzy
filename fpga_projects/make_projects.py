def write_guide(name, p):
    open(os.path.join(HERE, name, 'guide.html'), 'w', encoding='utf-8', newline='\n').write(guide_html(name, p))


def build(name):
    sys.path.insert(0, APP)
    from fpga import flow
    return flow.build(os.path.join(HERE, name), log=lambda s, c=None: print(s, flush=True), out_name=name)


def write_docs(names):
    cards, sections = [], []
    for n in names:
        p = load(n)
        cards.append('<a class="card" href="#%s"><span class="n">%s &middot; %s</span><h3>%s</h3><p>%s</p></a>'
                     % (n, html.escape(p['category']), html.escape(p['level']), html.escape(p['title']), html.escape(p['summary'])))
        sections.append('<section id="%s" class="project">%s<p><a href="#top">Back to the list</a></p></section>'
                        % (n, guide_html(n, p, standalone=False).replace('<h1>', '<h2>').replace('</h1>', '</h2>')))
    intro = open(os.path.join(HERE, 'docs_intro.html'), encoding='utf-8').read()
    page = ('<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">'
            '<title>Ardzy FPGA Projects</title><link rel="stylesheet" href="docs.css"></head><body id="top">'
            '<header class="top"><div class="wrap"><nav class="back"><a href="index.html">&larr; All documents</a></nav>'
            '<div class="kicker">Document 6 &middot; Project 2_Ardzy</div><h1>FPGA projects: ready to upload</h1>'
            '<p>Every idea as a complete project: the design, a prebuilt bitstream, a demo, a self-test, live controls in the app and a guide.</p>'
            '</div></header><main class="wrap">%s<div class="cards">%s</div>%s</main></body></html>'
            % (intro, ''.join(cards), ''.join(sections)))
    open(os.path.join(DOCS, '06_FPGA_Projects.html'), 'w', encoding='utf-8', newline='\n').write(page)
    print('wrote', os.path.join(DOCS, '06_FPGA_Projects.html'))


def main():
    args = sys.argv[1:]
    names = [a for a in args if not a.startswith('--')]
    todo = [n for n in projects() if not names or n in names or any(n.startswith(x) for x in names)]
    for n in todo:
        p = load(n)
        write_xdc(n, p)
        shutil.copy(os.path.join(HERE, 'common', 'blocks.py'), os.path.join(HERE, n, 'blocks.py'))
        for f in p.get('extra_files', []):
            shutil.copy(os.path.join(HERE, 'common', f), os.path.join(HERE, n, f))
        if os.path.isfile(os.path.join(HERE, n, 'guide.md')):
            write_guide(n, p)
        print('%-20s %s' % (n, p['title']))
        if '--build' in args:
            build(n)
    if '--docs' in args:
        write_docs(projects())


if __name__ == '__main__':
    main()
