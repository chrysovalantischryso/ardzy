"""Builds the EBAZ4205 pin-control design (= the base design U-Boot loads at power-on, so the Ethernet works)
and writes its pin list for the board's tools.

    python boards/ebaz4205/fpga/make_pin_control.py

Out: boards/ebaz4205/fpga/ardzy_io.bit, boards/ebaz4205/io_map.json, boards/ebaz4205/fpga/ardzy_pins.xdc
(the template for your own designs: every header pin, commented out).
The core (ardzy_ctl.v, ardzy_io_core in ardzy_io_top.v) is the S9's, from projects/ardzy_io.
"""
import json, os, shutil, sys, tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, '..', '..', '..'))
sys.path.insert(0, os.path.join(ROOT, 'pc_app'))
sys.path.insert(0, os.path.join(ROOT, 'pc_app', 'fpga'))
from fpga import flow  # noqa: E402

B = json.load(open(os.path.join(HERE, '..', 'board.json'), encoding='utf-8'))
NUMS = ['5', '6', '7', '8', '9', '11', '13', '14', '15', '16', '17', '18', '19', '20']

# the 49 places of the core: (name the I/O view shows, port bit, package pin)
places = [None] * 49
for h, base in (('DATA1', 0), ('DATA2', 14)):
    for i, n in enumerate(NUMS):
        places[base + i] = ('%s-%s' % (h, n), '%s[%d]' % (h.lower(), i), B['headers'][h][n])
for i, n in enumerate(NUMS[:13]):
    places[28 + i] = ('DATA3-%s' % n, 'data3[%d]' % i, B['headers']['DATA3'][n])
places[45] = ('DATA3-20', 'data3[13]', B['headers']['DATA3']['20'])
places[46] = ('J5-PWM', 'j5_pwm', B['fans']['J5']['pwm'])

io_map = []
for k, p in enumerate(places):
    port, bit = ('gpio1', k) if k < 32 else ('gpio2', k - 32)
    name, _, pin = p if p else ('nc%d' % k, None, '')
    io_map.append({'port': port, 'bit': bit, 'name': name, 'pin': pin})
json.dump(io_map, open(os.path.join(HERE, '..', 'io_map.json'), 'w'), indent=1)

xdc = ['# EBAZ4205 pin-control design (generated by make_pin_control.py)']
for p in places:
    if p:
        xdc.append('set_property -dict {PACKAGE_PIN %s IOSTANDARD LVCMOS33} [get_ports {%s}]' % (p[2], p[1]))
xdc.append('set_property -dict {PACKAGE_PIN %s IOSTANDARD LVCMOS33} [get_ports fan_pwm]' % B['fans']['J3']['pwm'])
xdc.append('set_property -dict {PACKAGE_PIN %s IOSTANDARD LVCMOS33} [get_ports j3_tach]' % B['fans']['J3']['tach'])
xdc.append('set_property -dict {PACKAGE_PIN %s IOSTANDARD LVCMOS33} [get_ports j5_tach]' % B['fans']['J5']['tach'])

# the template for users: every pin, commented out
tpl = ['# EBAZ4205 pins for your design: remove the # in front of the pins you use and name the port as in',
       '# your top module. All are 3.3 V FPGA pins with no protection. The Ethernet pins and the two LEDs',
       '# are connected by the Ardzy build itself (use the LEDs: name a port and uncomment its line).', '']
for h in ('DATA1', 'DATA2', 'DATA3'):
    tpl.append('# %s header' % h)
    for n in NUMS:
        tpl.append('#set_property -dict {PACKAGE_PIN %s IOSTANDARD LVCMOS33} [get_ports {%s_%s}]' % (B['headers'][h][n], h.lower(), n))
    tpl.append('')
tpl.append('# on-board LEDs (on when the pin is 0)')
for name, led in B['leds'].items():
    tpl.append('#set_property -dict {PACKAGE_PIN %s IOSTANDARD LVCMOS33} [get_ports {led_%s_n}]' % (led['pin'], name))
tpl += ['', '# fan headers J3 / J5: PWM out, speed in']
for f, d in B['fans'].items():
    tpl.append('#set_property -dict {PACKAGE_PIN %s IOSTANDARD LVCMOS33} [get_ports {%s_pwm}]' % (d['pwm'], f.lower()))
    tpl.append('#set_property -dict {PACKAGE_PIN %s IOSTANDARD LVCMOS33} [get_ports {%s_tach}]' % (d['tach'], f.lower()))
tpl += ['', '# 50 MHz oscillator X5 (only on boards that have it mounted)',
        '#set_property -dict {PACKAGE_PIN %s IOSTANDARD LVCMOS33} [get_ports {clk50}]' % B['clock_pin']['pin']]
open(os.path.join(HERE, 'ardzy_pins.xdc'), 'w', newline='\n').write('\n'.join(tpl) + '\n')

if '--no-build' in sys.argv:
    sys.exit(0)
work = os.path.join(tempfile.gettempdir(), 'ardzy_io_ebaz')
shutil.rmtree(work, ignore_errors=True)
os.makedirs(work)
for f in ('ardzy_ctl.v', 'ardzy_io_top.v'):
    shutil.copy(os.path.join(ROOT, 'projects', 'ardzy_io', f), work)
shutil.copy(os.path.join(HERE, 'ardzy_io_ebaz.v'), work)
open(os.path.join(work, 'pins.xdc'), 'w').write('\n'.join(xdc) + '\n')
json.dump({'top': 'ardzy_io_ebaz', 'board': 'ebaz4205'}, open(os.path.join(work, 'fpga.json'), 'w'))
bit = flow.build(work, log=lambda t, k=None: print(t), out_name='ardzy_io')
shutil.copy(bit, os.path.join(HERE, 'ardzy_io.bit'))
print('wrote', os.path.join(HERE, 'ardzy_io.bit'))
