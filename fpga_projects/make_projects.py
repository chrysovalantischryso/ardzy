CONNECTOR_PIN = {0: 5, 1: 11, 2: 12, 3: 15}         # jN[k] -> pin number on the 18-pin connector


def pin_label(name):
    m = re.fullmatch(r'j(\d)\[(\d)\]', name)
    if m:
        return 'J%s pin %d' % (m.group(1), CONNECTOR_PIN[int(m.group(2))])
    return {'i2c1_scl': 'SCL, J1..J8 pin 4', 'i2c1_sda': 'SDA, J1..J8 pin 3', 'i2c2_scl': 'SCL, J9 pin 4',
            'i2c2_sda': 'SDA, J9 pin 3'}.get(name, name)


def projects():
    return sorted(d for d in os.listdir(HERE) if re.match(r'\d\d_', d) and os.path.isfile(os.path.join(HERE, d, 'project.json')))


def load(name):
    return json.load(open(os.path.join(HERE, name, 'project.json'), encoding='utf-8'))


def write_xdc(name, p):
    lines = ['# Generated by fpga_projects/make_projects.py from project.json: edit the "pins" there.']
    for port, pin in p['pins'].items():
        if pin not in PINS:
            raise ValueError('%s: unknown board pin %s' % (name, pin))
        lines.append('set_property PACKAGE_PIN %s [get_ports {%s}]' % (PINS[pin], port))
        lines.append('set_property IOSTANDARD LVCMOS33 [get_ports {%s}]' % port)
        if pin.startswith(('j', 'i2c')) or port in p.get('pullup', []):
            lines.append('set_property PULLTYPE PULLUP [get_ports {%s}]' % port)
    # clocks made inside the FPGA (MMCM / PLL outputs): nextpnr does not work out their speed itself
    for net, mhz in p.get('clocks', {}).items():
        lines.append('create_clock -period %.3f [get_nets %s]' % (1000.0 / mhz, net))
    open(os.path.join(HERE, name, 'pins.xdc'), 'w', newline='\n').write('\n'.join(lines) + '\n')


# ---------------------------------------------------------------- a small Markdown -> HTML converter
def _inline(s):
    s = html.escape(s, quote=False)
    s = re.sub(r'`([^`]+)`', r'<code>\1</code>', s)
    s = re.sub(r'\*\*([^*]+)\*\*', r'<b>\1</b>', s)
    s = re.sub(r'(?<![\w*])\*([^*\n]+)\*(?![\w*])', r'<i>\1</i>', s)
    s = re.sub(r'\[([^\]]+)\]\((https?://[^)]+)\)', r'<a href="\2" target="_blank" rel="noopener">\1</a>', s)
    return s


def md_to_html(md):
    out, i, lines = [], 0, md.replace('\r\n', '\n').split('\n')
    while i < len(lines):
        l = lines[i]
        if l.startswith('```'):
            j = i + 1
            while j < len(lines) and not lines[j].startswith('```'):
                j += 1
            out.append('<pre><code>%s</code></pre>' % html.escape('\n'.join(lines[i + 1:j]), quote=False))
            i = j + 1
            continue
        if l.startswith(('<svg', '<figure', '<details')):                     # raw drawings, fold-out answers
            j = i
            end = '</svg>' if l.startswith('<svg') else '</figure>' if l.startswith('<figure') else '</details>'
            while j < len(lines) and end not in lines[j]:
                j += 1
            out.append('\n'.join(lines[i:j + 1]))
            i = j + 1
            continue
        m = re.match(r'(#{1,4}) (.*)', l)
        if m:
            n = len(m.group(1)) + 1
            out.append('<h%d>%s</h%d>' % (n, _inline(m.group(2)), n))
            i += 1
            continue
        if l.startswith('|'):
            rows = []
            while i < len(lines) and lines[i].startswith('|'):
                if not re.match(r'^\|[\s:|-]+\|$', lines[i]):
                    rows.append([c.strip() for c in lines[i].strip('|').split('|')])
                i += 1
            t = ['<table>', '<tr>%s</tr>' % ''.join('<th>%s</th>' % _inline(c) for c in rows[0])]
            t += ['<tr>%s</tr>' % ''.join('<td>%s</td>' % _inline(c) for c in r) for r in rows[1:]]
            out.append('\n'.join(t + ['</table>']))
            continue
        m = re.match(r'> \*\*(ok|info|warn|bad)\*\* (.*)', l)
        if m:
            body = [m.group(2)]
            i += 1
            while i < len(lines) and lines[i].startswith('> '):
                body.append(lines[i][2:])
                i += 1
            out.append('<div class="box %s">%s</div>' % (m.group(1), _inline(' '.join(body))))
            continue
        if re.match(r'(\d+\.|-) ', l):
            ordered = l[0].isdigit()
            items = []
            while i < len(lines) and re.match(r'(\d+\.|-) ', lines[i]):
                items.append(re.sub(r'^(\d+\.|-) ', '', lines[i]))
                i += 1
                while i < len(lines) and lines[i].startswith('   ') and lines[i].strip():
                    items[-1] += ' ' + lines[i].strip()
                    i += 1
            tag = 'ol' if ordered else 'ul'
            out.append('<%s>%s</%s>' % (tag, ''.join('<li>%s</li>' % _inline(x) for x in items), tag))
            continue
        if not l.strip():
            i += 1
            continue
        para = [l]
        i += 1
        while i < len(lines) and lines[i].strip() and not re.match(r'(#|\||```|> |\d+\. |- |<svg|<figure|<details)', lines[i]):
            para.append(lines[i])
            i += 1
        out.append('<p>%s</p>' % _inline(' '.join(para)))
    return '\n'.join(out)


def facts_html(name, p):
    rows = ['<tr><th>Slot</th><th>Address</th><th>Block</th></tr>']
    for s, what in p.get('slots', {}).items():
        lo, hi = (int(x) for x in s.split('-')) if '-' in s else (int(s), int(s))
        addr = '0x%08X' % (0x43C00000 + lo * 0x1000) + ('' if hi == lo else ' .. 0x%08X' % (0x43C00FFF + hi * 0x1000))
        rows.append('<tr><td>%s</td><td><code>%s</code></td><td>%s</td></tr>' % (s, addr, html.escape(what)))
    pins = ['<tr><th>Signal</th><th>Board pin</th><th>FPGA pin</th></tr>']
    for port, pin in p['pins'].items():
        if not port.startswith('leds['):
            pins.append('<tr><td><code>%s</code></td><td>%s</td><td>%s</td></tr>' % (html.escape(port), pin_label(pin), PINS[pin]))
    wiring = ''
    if p.get('wiring'):
        wiring = '<h3>Wiring</h3><table><tr><th>Board</th><th>Goes to</th><th>Note</th></tr>%s</table>' % ''.join(
            '<tr><td>%s</td><td>%s</td><td>%s</td></tr>' % tuple(html.escape(x) for x in w) for w in p['wiring'])
    parts = ''
    if p.get('parts'):
        parts = '<h3>Parts</h3><ul>%s</ul>' % ''.join('<li>%s</li>' % html.escape(x) for x in p['parts'])
    tested = ''
    if p.get('tested'):
        tested = '<div class="box ok"><b>Tested on the real board</b> %s</div>' % html.escape(p['tested'])
    return ('%s<h3>Registers (ARM side)</h3><table>%s</table><h3>Pins</h3><table>%s</table>%s%s'
            % (tested, ''.join(rows), ''.join(pins), wiring, parts))


def guide_html(name, p, standalone=True):
    md = open(os.path.join(HERE, name, 'guide.md'), encoding='utf-8').read()
    body = md_to_html(md)
    head = ('<div class="kicker">%s &middot; %s</div><h1>%s</h1><p class="lead">%s</p>'
            % (html.escape(p['category']), html.escape(p['level']), html.escape(p['title']), html.escape(p['summary'])))
    content = head + facts_html(name, p) + body
    if not standalone:
        return content
    return ('<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">'
            '<title>%s</title><style>%s</style></head><body><main class="wrap">%s</main></body></html>'
            % (html.escape(p['title']), GUIDE_CSS, content))


