def glyph(ch):
    """7 x 5 array of 0 / 1 for a character (unknown ones are a small box)."""
    rows = _GLYPHS.get(ch.upper()) or ['.....', '.###.', '.#.#.', '.#.#.', '.#.#.', '.###.', '.....']
    return np.array([[c == '#' for c in r] for r in rows], np.uint8)


def chars():
    return ''.join(sorted(_GLYPHS))


def render(text, scale=1, gap=1):
    """Text -> 2-D uint8 array of 0 / 1 (7 * scale high), `gap` empty columns between characters."""
    cols = []
    for i, ch in enumerate(text):
        g = glyph(ch)
        cols.append(g)
        if i < len(text) - 1:
            cols.append(np.zeros((7, gap), np.uint8))
    a = np.concatenate(cols, axis=1) if cols else np.zeros((7, 1), np.uint8)
    if scale > 1:
        a = np.kron(a, np.ones((scale, scale), np.uint8))
    return a


